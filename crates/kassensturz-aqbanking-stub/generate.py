"""Writes src/generated.rs: a default stub for every function the bindings
declare that src/lib.rs doesn't implement by hand. Run from the crate's
folder after bindgen/generate.sh changed the declarations (D-060)."""
import re, sys, pathlib

here = pathlib.Path(__file__).resolve().parent
sys_src = here.parent / "kassensturz-aqbanking-sys" / "src"
hand = pathlib.Path(here / "src" / "lib.rs").read_text()
hand_written = set(re.findall(r'pub unsafe extern "C" fn (\w+)\(', hand))
hand_written |= set(re.findall(r'(?:getter|next_getter|setter)!\(\s*(\w+),', hand))
field = re.compile(r'pub (\w+):\s*unsafe extern "C" fn\(')


def declared(text):
    """Every function field of the bindgen struct: (name, args, return
    type). Declarations wrap over several lines and arguments can hold
    nested parentheses (callback types), so the parentheses are matched by
    counting, not by a regular expression."""
    for m in field.finditer(text):
        start = m.end()
        depth, i = 1, start
        while depth:
            depth += {"(": 1, ")": -1}.get(text[i], 0)
            i += 1
        args = text[start:i - 1]
        rest = text[i:]
        ret = ""
        if rest.lstrip().startswith("->"):
            j, depth = rest.index("->") + 2, 0
            while not (depth == 0 and rest[j] == ","):
                depth += {"(": 1, "<": 1, ")": -1, ">": -1}.get(rest[j], 0)
                j += 1
            ret = rest[rest.index("->") + 2:j]
        yield m.group(1), args, ret

# REUSE-IgnoreStart: the header of the generated file, not of this one.
out = ["// SPDX-FileCopyrightText: 2026 KassenSturz contributors",
       "// SPDX-License-Identifier: GPL-3.0-or-later",
# REUSE-IgnoreEnd
       "",
       "//! Generated by generate.py: a stub for every declared function that",
       "//! lib.rs doesn't implement. Each answers with nothing (null, zero).",
       "",
       "#![allow(non_snake_case, unused_variables, clippy::missing_safety_doc)]",
       "",
       "use kassensturz_aqbanking_sys::aqbanking::*;",
       "use kassensturz_aqbanking_sys::gwenhywfar::*;",
       ""]
count = 0
for name in ("gwenhywfar", "aqbanking"):
    text = (sys_src / f"{name}.rs").read_text()
    for fname, args, ret in declared(text):
        args, ret = " ".join(args.split()), " ".join(ret.split())
        if fname in hand_written:
            continue
        args = args.rstrip(",")
        if ret:
            if ret.startswith("*"):
                body = "::std::ptr::null_mut()" if "*mut" in ret else "::std::ptr::null()"
            elif ret.startswith("::std::option::Option") or ret.startswith("GWEN_GUI_") and ret.endswith("_FN"):
                body = "None"
            else:
                body = "0"
            out.append(f'#[unsafe(no_mangle)]\npub unsafe extern "C" fn {fname}({args}) -> {ret} {{\n    {body}\n}}')
        else:
            out.append(f'#[unsafe(no_mangle)]\npub unsafe extern "C" fn {fname}({args}) {{}}')
        count += 1
(here / "src" / "generated.rs").write_text("\n".join(out) + "\n")
print(f"{count} default stubs, {len(hand_written)} hand-written")
