# Regenerates src/gwenhywfar.rs and src/aqbanking.rs with bindgen (D-060).
#
# Run it only when AqBanking or Gwenhywfar is upgraded (D-138); the output is
# committed, so normal builds need neither bindgen nor the C headers. It needs:
#   - bindgen-cli 0.73.2 (`cargo install bindgen-cli --version 0.73.2 --locked`,
#     a developer tool, see docs/THIRD_PARTY.md) and libclang,
#   - the development headers and shared libraries of exactly AqBanking 6.9.2
#     and Gwenhywfar 5.14.1, found through pkg-config (on Kubuntu 26.10:
#     libaqbanking-dev, libgwenhywfar-core-dev),
#   - nm (binutils) and cargo with rustfmt, for the checks and formatting.
#
# What goes in is decided by the allowlists below: the functions reading
# balances and statements needs, setting up a bank login, Gwenhywfar's GUI
# callbacks, dates, string lists and buffers. What stays out, on purpose:
#   - every floating-point amount function and the lossy `long` accessors of
#     AB_VALUE (D-141, threat T-10): amounts are read as the fraction's text,
#   - every command that moves money (D-053, T-14): transfers, debit notes,
#     standing orders, dated transfers, phone top-ups,
#   - Gwenhywfar's password store and password database (T-01): a PIN is
#     answered by KassenSturz's own callbacks, never saved by Gwenhywfar,
#   - AqBanking's file importers and exporters (KassenSturz has its own),
#     securities, documents and transaction limits (not needed for reading).
# After generating, the script checks that every declared function is really
# exported by the library it will be loaded from, that none of the excluded
# names slipped in, and prints the counts (AGENTS.md §9.4: scripted edits
# report their match count).
set -eu

here=$(cd "$(dirname "$0")" && pwd)
src="$here/../src"
BINDGEN=${BINDGEN:-bindgen}
NM=${NM:-nm}

expect_version() {
    if [ "$2" != "$3" ]; then
        echo "generate.sh: $1 is $2, but the bindings are made for $3" >&2
        exit 1
    fi
}
expect_version "bindgen" "$("$BINDGEN" --version)" "bindgen 0.73.2"
expect_version "Gwenhywfar" "$(pkg-config --modversion gwenhywfar)" "5.14.1"
expect_version "AqBanking" "$(pkg-config --modversion aqbanking)" "6.9.2"

cflags=$(pkg-config --cflags aqbanking gwenhywfar)
# With PKG_CONFIG_SYSROOT_DIR set (headers and libraries unpacked from a
# distribution's packages), pkg-config prepends it here as well.
libdir=$(pkg-config --variable=libdir gwenhywfar)

common="--rust-target 1.98 --rust-edition 2024 --formatter prettyplease
        --dynamic-link-require-all --no-layout-tests --no-doc-comments
        --no-prepend-enum-name --wrap-unsafe-ops --sort-semantically"

header='// SPDX-FileCopyrightText: 2026 KassenSturz contributors
// SPDX-License-Identifier: GPL-3.0-or-later
//
// GENERATED by bindgen 0.73.2 through bindgen/generate.sh from the headers of
// %s (D-060). Do not edit by hand: change the allowlists in that
// script and run it again.
#![allow(
    missing_docs,
    non_camel_case_types,
    non_snake_case,
    non_upper_case_globals,
    clippy::missing_safety_doc,
    clippy::too_many_arguments,
    clippy::type_complexity,
    clippy::unreadable_literal
)]'

# Gwenhywfar: libgwenhywfar.so.79 (D-138).
# shellcheck disable=SC2086
"$BINDGEN" "$here/gwenhywfar.h" -o "$src/gwenhywfar.rs" \
    $common \
    --dynamic-loading Gwenhywfar \
    --raw-line "$(printf "$header" "Gwenhywfar 5.14.1")" \
    --allowlist-function 'GWEN_(Init|Fini|Version)' \
    --allowlist-function 'GWEN_Error_SimpleToString' \
    --allowlist-function 'GWEN_Logger_(Exists|IsOpen|Open|Close|SetLevel|GetLevel|Name2Level|Level2Name)' \
    --allowlist-function 'GWEN_Gui_(new|free|SetGui|GetGui|GetFlags|SetFlags|AddFlags|SubFlags|GetName|SetName|SetCharSet|GetCharSet|UseDialogs)' \
    --allowlist-function 'GWEN_Gui_(GetPassword|SetPasswordStatus|CheckCert|LogHook|MessageBox|InputBox|ShowBox|HideBox|ShowError)' \
    --allowlist-function 'GWEN_Gui_(ProgressStart|ProgressAdvance|ProgressSetTotal|ProgressLog|ProgressLog2|ProgressEnd|GetMinProgressLogLevel|SetMinProgressLogLevel)' \
    --allowlist-function 'GWEN_Gui_(ExecDialog|OpenDialog|CloseDialog|RunDialog)' \
    --allowlist-function 'GWEN_Gui_Set(GetPassword|SetPasswordStatus|CheckCert|LogHook|MessageBox|InputBox|ShowBox|HideBox|ProgressStart|ProgressAdvance|ProgressSetTotal|ProgressLog|ProgressEnd|ExecDialog|OpenDialog|CloseDialog|RunDialog|GetFileName|WaitForSockets|ReadDialogPrefs|WriteDialogPrefs)Fn' \
    --allowlist-function 'GWEN_SslCertDescr_(GetStatusFlags|GetStatusText|GetIsError|GetFingerPrint|GetFingerPrintSha1|GetFingerPrintSha512|GetCommonName|GetOrganizationName|GetOrganizationalUnitName|GetCountryName|GetLocalityName|GetStateOrProvinceName|GetIpAddress|GetNotBefore|GetNotAfter)' \
    --allowlist-function 'GWEN_Date_(free|dup|fromGregorian|fromString|fromStringWithTemplate|CurrentDate|GetYear|GetMonth|GetDay|GetString|toStringWithTemplate|Compare|AddDays|SubDays)' \
    --allowlist-function 'GWEN_Time_(free|toString|toUtcString|Seconds|GetBrokenDownUtcDate)' \
    --allowlist-function 'GWEN_StringList_(new|free|Count|FirstEntry|AppendString|StringAt)' \
    --allowlist-function 'GWEN_StringListEntry_(Data|Next)' \
    --allowlist-function 'GWEN_Buffer_(new|free|GetStart|GetUsedBytes|AppendString|AppendBytes|Reset)' \
    --allowlist-function 'GWEN_DB_(Group_new|Group_free|GetGroup|GetFirstGroup|GetNextGroup|GroupName|GetFirstVar|GetNextVar|VariableName|GetCharValue|SetCharValue|GetIntValue|SetIntValue|DeleteGroup|DeleteVar)' \
    --allowlist-var 'GWENHYWFAR_VERSION_.*' \
    --allowlist-var 'GWEN_ERROR_.*' \
    --allowlist-var 'GWEN_GUI_.*' \
    --allowlist-var 'GWEN_SSL_CERT_FLAGS_.*' \
    --allowlist-var 'GWEN_DB_FLAGS_.*' \
    --allowlist-var 'GWEN_PATH_FLAGS_.*' \
    --allowlist-var 'GWEN_LOGGER_.*' \
    --allowlist-type 'GWEN_LOGGER_LEVEL' \
    --allowlist-type 'GWEN_GUI_PASSWORD_(STATUS|METHOD)' \
    --allowlist-type 'GWEN_GUI_FILENAME_TYPE' \
    -- $cflags

# AqBanking: libaqbanking.so.44 (D-138). The Gwenhywfar types it uses come
# from the module above, so they exist once (blocklisted here, imported by
# the raw line).
# shellcheck disable=SC2086
"$BINDGEN" "$here/aqbanking.h" -o "$src/aqbanking.rs" \
    $common \
    --dynamic-loading AqBanking \
    --raw-line "$(printf "$header" "AqBanking 6.9.2")" \
    --raw-line 'use super::gwenhywfar::*;' \
    --blocklist-type 'GWEN_.*' \
    --blocklist-function 'GWEN_.*' \
    --blocklist-item 'GWEN_.*' \
    --allowlist-function 'AB_Banking_(new|free|Init|Fini|GetVersion|GetAppName|GetUserDataDir|GetSharedDataDir)' \
    --allowlist-function 'AB_Banking_RuntimeConfig_(Get|Set)(Char|Int)Value' \
    --allowlist-function 'AB_Banking_(GetAccountSpecList|GetAccountSpecByUniqueId|GetAccountSpecByAlias|SendCommands)' \
    --allowlist-function 'AB_Banking_(GetBankInfo|GetBankInfoByTemplate|CheckIban|CheckAccount|MakeGermanIban)' \
    --allowlist-function 'AB_Banking_(ProviderControl|GetNewUserDialog|CreateSetupDialog)' \
    --allowlist-function 'AB_AccountSpec_(free|List_(First|Next|free|GetCount|GetByUniqueId))' \
    --allowlist-function 'AB_AccountSpec_Get(Type|UniqueId|BackendName|OwnerName|AccountName|Currency|Iban|Bic|BankCode|BankName|BranchId|AccountNumber|SubAccountNumber|Country|Memo)' \
    --allowlist-function 'AB_Transaction_(new|free|dup|Get[A-Za-z0-9]*)' \
    --allowlist-function 'AB_Transaction_Set(Command|UniqueAccountId|FirstDate|LastDate)' \
    --allowlist-function 'AB_Transaction_(Command|Type|SubType|Status)_(toString|fromString)' \
    --allowlist-function 'AB_Transaction_List_(First|Next|free|GetCount)' \
    --allowlist-function 'AB_Transaction_List2_(new|free|freeAll|PushBack|First|GetFront|GetSize|Clear)' \
    --allowlist-function 'AB_Transaction_List2Iterator_(Data|Next|free)' \
    --allowlist-function 'AB_Value_(new|free|dup|fromString|fromInt|toString|toHumanReadableString|toHbciString|GetNumDenomString|GetCurrency|SetCurrency|IsNegative|IsPositive|IsZero|Compare|Equal|Negate|SetZero|AddValue|SubValue)' \
    --allowlist-function 'AB_Balance_(free|GetType|GetDate|GetValue|Type_toString)' \
    --allowlist-function 'AB_Balance_List_(First|Next|free|GetCount|GetLatestByType)' \
    --allowlist-function 'AB_ImExporterContext_(new|free|Clear|GetAccountInfoList|GetAccountInfoCount|GetFirstAccountInfo|GetMessageList|GetFirstMessage)' \
    --allowlist-function 'AB_ImExporterAccountInfo_(free|List_(First|Next|free|GetCount|GetByIban|GetByAccountId))' \
    --allowlist-function 'AB_ImExporterAccountInfo_Get(AccountNumber|BankCode|Iban|Bic|Currency|AccountName|OwnerName|Owner|AccountType|AccountId|SubAccountId|BankName|Country|Description|TransactionList|TransactionCount|BalanceList|FirstTransaction|FirstBalance)' \
    --allowlist-function 'AB_BankInfo_(free|List2_(new|free|freeAll|First|GetFront|GetSize)|List2Iterator_(Data|Next|free))' \
    --allowlist-function 'AB_BankInfo_(new|Set(Country|BankId|Bic|BankName|Location|City))' \
    --allowlist-function 'AB_BankInfo_Get(Country|BranchId|BankId|Bic|BankName|Location|Street|Zipcode|City|Region|Phone|Fax|Email|Website|Services)' \
    --allowlist-function 'AB_BankInfoService_List_(First|Next|GetCount)' \
    --allowlist-function 'AB_BankInfoService_Get(Type|Address|Suffix|Pversion|Hversion|Mode|UserFlags|Aux1|Aux2|Aux3|Aux4)' \
    --allowlist-function 'AB_Message_List_(First|Next|GetCount)' \
    --allowlist-function 'AB_Message_Get(Source|Subject|Text|DateReceived|UserId|AccountId)' \
    --allowlist-var 'AQBANKING_VERSION_.*' \
    --allowlist-var 'AB_ERROR_.*' \
    --allowlist-var 'AB_BANKING_EXTENSION_.*' \
    --allowlist-type 'AB_(ACCOUNT_TYPE|BALANCE_TYPE|TRANSACTION_(TYPE|SUBTYPE|STATUS|COMMAND|PERIOD|CHARGE|SEQUENCE))' \
    --blocklist-item 'AB_Transaction_Command(Transfer|DebitNote|InternalTransfer|LoadCellPhone|(Create|Modify|Delete)(StandingOrder|DatedTransfer))' \
    --blocklist-item 'AB_Transaction_CommandSepa(Transfer|DebitNote|FlashDebitNote|InternalTransfer|(Create|Modify|Delete)(StandingOrder|DatedTransfer))' \
    --blocklist-function 'AB_Value_(GetValueAsDouble|SetValueFromDouble|fromDouble|toDbFloat|Num|Denom|MultValue|DivValue|fromDb|toDb|Dump)' \
    -- $cflags

# bindgen keeps every variant of an enum it needs, so the commands that move
# money are removed here (D-053, T-14): 20 of AB_TRANSACTION_COMMAND's
# variants (R9: the count is checked). AB_Transaction_SetCommand stays, for
# the reading commands that are left.
payments='AB_Transaction_Command(Sepa)?(Transfer|DebitNote|FlashDebitNote|InternalTransfer|LoadCellPhone|(Create|Modify|Delete)(StandingOrder|DatedTransfer))'
removed=$(grep -cE "^pub const $payments: " "$src/aqbanking.rs")
if [ "$removed" != "20" ]; then
    echo "generate.sh: expected 20 payment commands to remove, found $removed" >&2
    exit 1
fi
sed -i -E "/^pub const $payments: /d" "$src/aqbanking.rs"
echo "$src/aqbanking.rs: removed $removed payment commands"

# Every function the bindings declare must be exported by the library it is
# loaded from: with --dynamic-link-require-all one missing symbol makes the
# whole library count as "not installed" (D-138), so a wrong name would hide
# AqBanking from every user.
check_exports() {
    file=$1
    library=$2
    sed -n 's/^    pub \([A-Za-z0-9_]*\): unsafe extern "C" fn.*/\1/p' "$file" | sort -u > "$file.wanted.tmp"
    count=$(grep -c . "$file.wanted.tmp")
    "$NM" -D --defined-only "$library" | awk '{print $3}' | sort -u > "$file.exported.tmp"
    missing=$(comm -23 "$file.wanted.tmp" "$file.exported.tmp")
    rm -f "$file.wanted.tmp" "$file.exported.tmp"
    if [ -n "$missing" ]; then
        echo "generate.sh: $file declares functions that $library does not export:" >&2
        echo "$missing" >&2
        exit 1
    fi
    echo "$file: $count functions, all exported by $library"
}
check_exports "$src/gwenhywfar.rs" "$libdir/libgwenhywfar.so.79"
check_exports "$src/aqbanking.rs" "$libdir/libaqbanking.so.44"

# Nothing excluded on purpose may come back through a transitive dependency.
forbidden="GetValueAsDouble|SetValueFromDouble|fromDouble|toDbFloat|AB_Value_Num\\b|AB_Value_Denom\\b|$payments|PasswdStore|PasswordDb|\\bf32\\b|\\bf64\\b"
if grep -nE "$forbidden" "$src/gwenhywfar.rs" "$src/aqbanking.rs"; then
    echo "generate.sh: an excluded name is in the generated bindings (see above)" >&2
    exit 1
fi
echo "no excluded name in the bindings"

(cd "$here/../../.." && cargo fmt --package kassensturz-aqbanking-sys)
echo "formatted"
