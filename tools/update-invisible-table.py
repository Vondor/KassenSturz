"""Build crates/kassensturz-ai-tools/src/invisible_table.rs (D-787, B-300).

The AI tools hide every code point a model could read but a person cannot
see (see `hides_text` in text.rs). Instead of a list typed by hand, the table
holds, from the Unicode Character Database as Python's `unicodedata` ships
it: every code point of the general categories Cf (format), Co (private use)
and Cn (unassigned, so a character added later is hidden too until a person
has looked at it), the variation selectors and the Other_Default_Ignorable
code points that are letters or marks (the Hangul and Khmer fillers, the
combining grapheme joiner). Run it again when a new Unicode version comes
out; `--check` compares the file with what this Python would write and stays
silent when the Python's Unicode version is not the file's.

    tools/update-invisible-table.py          write the file
    tools/update-invisible-table.py --check  compare it
"""

import pathlib
import sys
import unicodedata

TARGET = pathlib.Path(__file__).resolve().parent.parent / (
    "crates/kassensturz-ai-tools/src/invisible_table.rs"
)

# Variation selectors: Mongolian, standard, supplementary (UCD: Variation_Selector).
VARIATION_SELECTORS = [(0x180B, 0x180D), (0x180F, 0x180F), (0xFE00, 0xFE0F), (0xE0100, 0xE01EF)]
# Other_Default_Ignorable_Code_Point that are not in Cf, Co or Cn.
OTHER_IGNORABLE = [(0x034F, 0x034F), (0x115F, 0x1160), (0x17B4, 0x17B5), (0x3164, 0x3164), (0xFFA0, 0xFFA0)]


def ranges():
    hidden = set()
    for code in range(0x110000):
        if unicodedata.category(chr(code)) in ("Cf", "Co", "Cn"):
            hidden.add(code)
    for first, last in VARIATION_SELECTORS + OTHER_IGNORABLE:
        hidden.update(range(first, last + 1))
    # Surrogates are not `char`s in Rust, so they are left out.
    hidden -= set(range(0xD800, 0xE000))
    out = []
    for code in sorted(hidden):
        if out and out[-1][1] + 1 == code:
            out[-1][1] = code
        else:
            out.append([code, code])
    return out


def text():
    # REUSE-IgnoreStart
    lines = [
        "// SPDX-FileCopyrightText: 2026 KassenSturz contributors",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        "//! Generated by tools/update-invisible-table.py; do not edit by hand.",
        f"//! Unicode version of the source data: {unicodedata.unidata_version}",
        "//! (Python's `unicodedata`). Code points a model could read but a person",
        "//! cannot see: categories Cf, Co and Cn, variation selectors and the other",
        "//! default-ignorable letters and marks (D-787, B-300).",
        "",
        "/// Sorted, non-overlapping, inclusive ranges.",
        "pub(crate) const HIDDEN: &[(u32, u32)] = &[",
    ]
    # REUSE-IgnoreEnd
    for first, last in ranges():
        lines.append(f"    (0x{first:X}, 0x{last:X}),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    new = text()
    if "--check" in sys.argv:
        old = TARGET.read_text()
        version = f"source data: {unicodedata.unidata_version}"
        if version not in old:
            print(f"skipped: this Python knows Unicode {unicodedata.unidata_version}, the file another version")
            return 0
        if old != new:
            print("invisible_table.rs is out of date: run tools/update-invisible-table.py")
            return 1
        print("invisible_table.rs is current")
        return 0
    TARGET.write_text(new)
    print(f"wrote {TARGET} (Unicode {unicodedata.unidata_version})")
    return 0


sys.exit(main())
